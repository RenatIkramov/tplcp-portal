-- =====================================================================
-- V49. Поле в каталоге зовётся так, как в своём разделе
-- =====================================================================
-- V48 брала портальное название поля как min() подписи по всем
-- таблицам, где поле показывается. Выбор был «любой устойчиво» —
-- и оказался неверным для самых нужных полей.
--
-- У одного поля в разных таблицах подписи разные: в товарах
-- «Коммерческий код», в запасах «Код»; «Наименование товара» —
-- и «Наименование»; «Базовая единица измерения» — и «Ед.».
-- min() по алфавиту давал короткую подпись из запасов:
--
--   code → «Код» вместо «Коммерческий код»
--   name → «Наименование» вместо «Наименование товара»
--
-- А это ровно обязательные поля товара (code, name, unit): они
-- показываются во всех пяти таблицах, поэтому и расхождение подписей
-- именно у них. В списке переименования они были, но под именами,
-- которых администратор на экране товаров не видел, — то есть их
-- там как будто не было.
--
-- Правило теперь внятное: поле зовётся так, как его зовёт СВОЙ
-- раздел — таблица, одноимённая объекту (sku, orders, receipts,
-- stock, transfers). Остальные таблицы остаются в shown_in: где
-- подпись поменяется, видно по-прежнему.
--
-- Переименовывать обязательные поля можно и всегда было можно:
-- «обязательное» значит «нельзя скрыть от поклажедателя» (is_locked),
-- а не «нельзя переименовать». Запрета на это ни в базе,
-- ни в приложении нет.
SET search_path = dbo;

CREATE OR REPLACE FUNCTION admin_field_catalog(p_locale text)
RETURNS TABLE (
  object_code   varchar(20),
  object_name   varchar(100),
  field_id      varchar(100),
  portal_label  text,
  shown_in      text
)
LANGUAGE sql
STABLE
SET search_path = dbo
AS $$
  WITH texts AS (SELECT t.text_key, t.value FROM ui_texts(p_locale) t)
  SELECT
    o.code,
    o.name,
    c.field_id,
    -- подпись своего раздела; если поле показывается только
    -- в подчинённых таблицах (строки документа), берём первую
    -- по имени таблицы — лишь бы выбор не зависел от погоды
    (array_agg(COALESCE(t.value, c.text_key)::text
               ORDER BY (c.table_key = o.code) DESC, c.table_key))[1] AS portal_label,
    string_agg(DISTINCT c.table_key, ', ' ORDER BY c.table_key) AS shown_in
  FROM table_column c
  JOIN enum_object_type o ON o.id = c.object_type_id
  LEFT JOIN texts t ON t.text_key = c.text_key
  WHERE c.field_id IS NOT NULL
  GROUP BY o.code, o.name, c.field_id
  ORDER BY o.code, 4
$$;

COMMENT ON FUNCTION admin_field_catalog(text) IS
  'Поля, которые поклажедателю можно переименовать: строка на поле, '
  'подпись — как в своём разделе, рядом таблицы, где подпись поменяется';
