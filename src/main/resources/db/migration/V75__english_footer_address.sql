-- ---------------------------------------------------------------------
-- V75. Последний английский текст с кириллицей
-- ---------------------------------------------------------------------
-- Разбор пункта пула «на экране смены пароля локализовано не всё»
-- вышел за пределы того экрана: проверили каталог целиком. Оказалось
-- лучше, чем значилось — ключей без английского нет ни одного, —
-- но один английский текст наполовину остался русским:
--
--   en: Demonstration UI prototype — all data is fictional
--       · с. Байсерке, ул. Султана Бейбарыса, 1
--
-- Перевели фразу, а адрес склада в конце не тронули. Адрес —
-- имя собственное, и переводить его незачем; но в английском тексте
-- он читается как недоделка, а не как решение. Пишем латиницей,
-- как пишут адрес в английском письме.
--
-- Решение спорное ровно настолько, насколько спорна транслитерация
-- вообще: если заказчик захочет оставить адрес кириллицей, это
-- одна строка назад. Зато проверка ниже с этого дня не даст
-- появиться СЛУЧАЙНОЙ кириллице в английских текстах — а таких
-- не бывает полезных.
UPDATE ui_text
   SET value = 'Demonstration UI prototype — all data is fictional'
               || ' · Warehouse: Baiserke, Sultan Beibarys st. 1'
 WHERE text_key = 'common.text.demonstration_ui_prototype_all_dat'
   AND locale_id = (SELECT locale_id FROM dictionary_locale WHERE code = 'en');

-- ---------------------------------------------------------------------
-- Проверка на месте
-- ---------------------------------------------------------------------
DO $check$
DECLARE
  left_over text;
BEGIN
  SELECT string_agg(t.text_key, ', ')
    INTO left_over
    FROM ui_text t
    JOIN dictionary_locale l ON l.locale_id = t.locale_id
   WHERE l.code = 'en' AND t.value ~ '[А-Яа-яЁё]';
  IF left_over IS NOT NULL THEN
    RAISE EXCEPTION 'в английских текстах осталась кириллица: %', left_over;
  END IF;
END
$check$;
