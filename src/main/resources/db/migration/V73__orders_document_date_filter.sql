-- ---------------------------------------------------------------------
-- V73. Дата документа — на панель заказов
-- ---------------------------------------------------------------------
-- Диапазон дат по умолчанию ставится только дате документа: дат
-- в справочнике девять, и заполнять их все значит задавать несколько
-- условий разом — документ с одной незаполненной датой исчезал бы
-- из списка без видимой причины.
--
-- У заказов на панели стояла дата ОТГРУЗКИ, а даты документа не было
-- вовсе. После этого правила список заказов стал открываться без
-- ограничения по дате — то есть целиком, за все годы. Для поступлений
-- и перемещений такого не случилось: там дата документа на панели
-- была с самого начала (V68).
--
-- Дата отгрузки с панели не убирается: она там не случайно — именно
-- по ней человек спрашивает «что уезжает на этой неделе». Просто
-- рядом появляется дата документа, и она же несёт диапазон
-- по умолчанию.
UPDATE table_column
   SET filter_default = true
 WHERE table_key = 'orders'
   AND column_id = 'date';

-- ---------------------------------------------------------------------
-- Проверка на месте
-- ---------------------------------------------------------------------
DO $check$
DECLARE
  missing text;
BEGIN
  -- У каждого из трёх списков дата документа обязана быть на панели:
  -- иначе список открывается целиком, и это замечают не сразу,
  -- а когда документов станет много.
  SELECT string_agg(t.table_key, ', ')
    INTO missing
    FROM (VALUES ('receipts'), ('orders'), ('transfers')) AS t(table_key)
   WHERE NOT EXISTS (SELECT 1
                       FROM table_column c
                      WHERE c.table_key = t.table_key
                        AND c.column_id = 'date'
                        AND c.filter_kind = 'date'
                        AND c.filter_default);
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'дата документа не на панели по умолчанию: %', missing;
  END IF;
END
$check$;
