-- =====================================================================
-- V65. Правила номера документа
-- =====================================================================
-- ФОРМАТ: [тип][YYMMDD][счётчик]
--
--   O261014001 — заказ, 14 октября 2026, первый за день
--   R261014002 — поступление того же дня
--   T261015001 — перемещение следующего дня, счёт снова с первого
--
-- Тип одной латинской буквой: O — заказ (order), R — поступление
-- (receipt), T — перемещение (transfer). Без разделителей: номер
-- набирают руками и диктуют по телефону, а дефисы в таком деле
-- только мешают.
--
-- СЧЁТЧИК — на тип и день, один на всех поклажедателей. Решение
-- заказчика. Следствие, которое надо знать: в номерах одного клиента
-- будут пропуски — между его документами попадают чужие. Если это
-- однажды станет мешать, разрез счётчика меняется в одном месте, здесь.
--
-- ДЕНЬ берётся тем же часом, что и дата создания документа
-- (current_date и now() — один и тот же часовой пояс базы). Номер
-- и дата документа обязаны говорить об одном дне: расхождение тут
-- не заметят, пока кто-нибудь не станет искать документ по номеру
-- за «тот день».
--
-- ЧЕГО НЕ ДЕЛАЕМ. Старые документы не переименовываются: ПН-001448
-- и прочие остаются как есть. Номер мог уже уйти в переписку, в WMS
-- или в ERP клиента, и менять его задним числом значит ломать ссылки
-- на документ вне портала. Новый формат начинается с новых документов.
SET search_path = dbo;

-- ---------------------------------------------------------------------
-- 1. Счётчик
-- ---------------------------------------------------------------------
-- Последовательность Postgres тут не годится: она не умеет считать
-- «в разрезе дня», а сбрасывать её по расписанию — значит однажды
-- проспать сброс. Поэтому таблица: одна строка на тип и день.
CREATE TABLE document_counter (
  doc_type varchar(20) NOT NULL,
  doc_day  date        NOT NULL,
  last_no  integer     NOT NULL,
  PRIMARY KEY (doc_type, doc_day)
);

COMMENT ON TABLE document_counter IS
  'Счётчик номеров документов: по одной строке на тип документа и день';

-- ---------------------------------------------------------------------
-- 2. Выдача номера
-- ---------------------------------------------------------------------
-- Подпись функции не меняется — её вызывает createDraft, и менять
-- вызов не придётся.
CREATE OR REPLACE FUNCTION next_document_no(p_type text)
RETURNS varchar
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = dbo
AS $number$
DECLARE
  v_prefix text;
  v_day    date := current_date;
  v_no     integer;
BEGIN
  v_prefix := CASE p_type
                WHEN 'receipts'  THEN 'R'
                WHEN 'orders'    THEN 'O'
                WHEN 'transfers' THEN 'T'
              END;
  -- Неизвестный тип — это ошибка в коде, а не ввод человека. Прежняя
  -- функция возвращала на него NULL, и документ сохранялся без номера.
  IF v_prefix IS NULL THEN
    RAISE EXCEPTION 'Неизвестный тип документа: %', p_type;
  END IF;

  -- Одним запросом: вставить или увеличить. Это атомарно — два
  -- человека, нажавшие «Сохранить» в одну секунду, получат разные
  -- номера без блокировок и без гонки. Через SELECT max(...) + 1
  -- они получили бы один и тот же.
  INSERT INTO document_counter (doc_type, doc_day, last_no)
  VALUES (p_type, v_day, 1)
  ON CONFLICT (doc_type, doc_day)
    DO UPDATE SET last_no = document_counter.last_no + 1
  RETURNING last_no INTO v_no;

  -- Три знака с ростом, а не жёсткие три. lpad на длинной строке
  -- не дополняет, а ОБРЕЗАЕТ: lpad('1000', 3, '0') возвращает '100'.
  -- То есть тысячный документ за день получил бы номер сотого —
  -- и уникальный индекс на document_no отверг бы сохранение.
  -- Предел, спрятанный в формате, — мина замедленного действия.
  RETURN (v_prefix
       || to_char(v_day, 'YYMMDD')
       || CASE WHEN v_no < 1000 THEN lpad(v_no::text, 3, '0')
               ELSE v_no::text END)::varchar;
END
$number$;

GRANT EXECUTE ON FUNCTION next_document_no(text) TO portal_app;

COMMENT ON FUNCTION next_document_no(text) IS
  'Следующий номер документа: [тип][YYMMDD][счётчик], счётчик на тип и день';

-- ---------------------------------------------------------------------
-- 3. Прежние последовательности
-- ---------------------------------------------------------------------
-- Их больше никто не вызывает. Оставить «на всякий случай» —
-- значит оставить второй, молчащий способ выдавать номера: однажды
-- кто-то позовёт его и получит номер в старом формате.
DROP SEQUENCE IF EXISTS seq_receipt_no;
DROP SEQUENCE IF EXISTS seq_order_no;
DROP SEQUENCE IF EXISTS seq_transfer_no;

-- ---------------------------------------------------------------------
-- 4. Проверка на месте
-- ---------------------------------------------------------------------
-- Миграция, которая создала функцию с опечаткой, узнается об этом
-- на первом документе пользователя. Лучше здесь.
DO $check$
DECLARE
  v_first  text;
  v_second text;
BEGIN
  v_first  := next_document_no('orders');
  v_second := next_document_no('orders');

  IF v_first !~ ('^O' || to_char(current_date, 'YYMMDD') || '[0-9]{3,}$') THEN
    RAISE EXCEPTION 'Номер не того вида: %', v_first;
  END IF;
  IF v_second = v_first THEN
    RAISE EXCEPTION 'Счётчик не увеличивается: % и %', v_first, v_second;
  END IF;

  -- За собой убираем: проверка не должна съедать живые номера.
  DELETE FROM document_counter WHERE doc_type = 'orders' AND doc_day = current_date;
END $check$;
