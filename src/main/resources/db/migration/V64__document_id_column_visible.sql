-- =====================================================================
-- V64. «ID документа» в списках показывается сразу
-- =====================================================================
-- ЗАЧЕМ. У документа три номера, и в списке они разные колонки:
--
--   «Номер»                 — номер документа в ERP клиента;
--   «ID документа»          — номер, который выдал портал;
--   «Номер документа в WMS» — номер на складе.
--
-- Колонка «Номер» заполнялась номером ПОРТАЛА — «чтобы не пустовала».
-- Выходило хуже пустоты: человек видел в поле «номер в ERP» чужое число
-- и считал его своим. Это исправлено в коде, и теперь «Номер» пуст
-- у документов, созданных в портале: номера в ERP у них и нет.
--
-- Значит в списке должна быть видна колонка, которая есть всегда.
-- «ID документа» была скрыта по умолчанию — открываем: список, в котором
-- строку нельзя назвать по номеру, бесполезен. Прятать её человек
-- по-прежнему вправе через ⚙ Колонки.
--
-- Тех, кто уже настроил себе колонки, это не затронет: их выбор хранится
-- отдельно, а is_default — только состояние «из коробки».
SET search_path = dbo;

UPDATE table_column
   SET is_default = true
 WHERE column_id = 'no'
   AND table_key IN ('receipts', 'orders', 'transfers');

DO $check$
DECLARE
  hidden text;
BEGIN
  SELECT string_agg(table_key, ', ')
    INTO hidden
    FROM table_column
   WHERE column_id = 'no'
     AND table_key IN ('receipts', 'orders', 'transfers')
     AND NOT is_default;
  IF hidden IS NOT NULL THEN
    RAISE EXCEPTION 'Колонка «ID документа» осталась скрытой: %', hidden;
  END IF;
END $check$;
