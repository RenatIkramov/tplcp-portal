-- =====================================================================
-- V55. Убрать ключи текстов, которые перестали использоваться
-- =====================================================================
-- V52 завела подписи таблиц для экрана видимости полей: «Документ»,
-- «Состав документа», «Детали строки», «Остатки», «Партии».
-- Через две миграции раскладка экрана поменялась:
--
--   * V53 разложила поля документов по вкладкам их карточки, и подписи
--     «Документ» и «Состав документа» заменились на настоящие названия
--     вкладок («Общая информация», «Состав поступления» и соседние);
--   * V54 переименовала вкладку запасов «Партии» в «Детали» и завела
--     под неё новый ключ.
--
-- Три ключа остались висеть без употребления. Держать их «на всякий
-- случай» хуже, чем удалить: ключ в экране переводов выглядит
-- действующей подписью, его переводят на нидерландский, а он нигде
-- не показывается. Удаляем — и пусть лучше что-нибудь упадёт сейчас,
-- на пустой базе разработчика, чем всплывёт у клиента.
--
-- Удаление пойдёт в таком порядке: сначала тексты, потом сам ключ.
-- Обратный порядок не пройдёт — на ui_text_key стоит внешний ключ,
-- и база сама не даст удалить ключ с переводами.
SET search_path = dbo;

-- ---------------------------------------------------------------------
-- 1. Проверка: ключи действительно свободны
-- ---------------------------------------------------------------------
-- На ui_text_key ссылаются две колонки каталога: text_key (подпись
-- колонки) и group_key (вкладка, на которой колонка показывается).
-- Если хоть одна ссылка осталась, миграция падает — это и значит
-- «пусть лучше упадёт сейчас».
DO $$
DECLARE
  v_used text;
BEGIN
  SELECT string_agg(DISTINCT k, ', ') INTO v_used
    FROM (
      SELECT text_key AS k FROM table_column
       WHERE text_key IN ('admin.table.batches', 'admin.table.document',
                          'admin.table.composition')
      UNION ALL
      SELECT group_key FROM table_column
       WHERE group_key IN ('admin.table.batches', 'admin.table.document',
                           'admin.table.composition')
    ) t;
  IF v_used IS NOT NULL THEN
    RAISE EXCEPTION 'Ключ ещё используется в каталоге колонок: %', v_used;
  END IF;
END $$;

-- ---------------------------------------------------------------------
-- 2. Удаление
-- ---------------------------------------------------------------------
DELETE FROM ui_text
 WHERE text_key IN ('admin.table.batches', 'admin.table.document',
                    'admin.table.composition');

DELETE FROM ui_text_key
 WHERE text_key IN ('admin.table.batches', 'admin.table.document',
                    'admin.table.composition');
