-- =====================================================================
-- V39. Единица измерения не повторяется
-- =====================================================================
-- V38 вывела enum_uom на экран «Справочники»: до этого справочник
-- никто не вёл, значения пришли из WMS один раз, и уникальность
-- держалась сама собой. Как только появилась кнопка «+ Добавить»,
-- стало возможно завести вторую «шт» — и тогда в карточке товара
-- человек выбирает между двумя одинаковыми строками, а в отчётах
-- одна и та же единица считается дважды.
--
-- Поэтому два ограничения. Обозначение — без учёта регистра:
-- «шт» и «ШТ» для человека одно и то же, и если разрешить обе,
-- то разбираться, какая из них «правильная», будет некому.
-- Код МКЕИ — как есть, он и так из цифр.
--
-- Проверено перед созданием: повторов в enum_uom нет.
SET search_path = dbo;

CREATE UNIQUE INDEX IF NOT EXISTS enum_uom_symbol_uq
    ON enum_uom (lower(symbol));

CREATE UNIQUE INDEX IF NOT EXISTS enum_uom_mkei_code_uq
    ON enum_uom (mkei_code);

-- Портал переводит нарушение этих ограничений в понятный отказ
-- (UnitService.save). Ограничение в базе — защита, сообщение
-- на экране — удобство; одно другое не заменяет.
