-- ---------------------------------------------------------------------
-- V99. Шаблон заказа: «Шапка заказа» → «Заголовок заказа»
-- ---------------------------------------------------------------------
-- Замечание заказчика от 03.11.2026. «Шапка» — жаргон; в шаблоне,
-- который уходит клиенту, таблица называется «Заголовок заказа».
-- Окно ошибок загрузки называет ту же таблицу — переименовано и там,
-- чтобы человек узнал в списке ошибок таблицу из файла.
SET search_path = dbo;

UPDATE ui_text t
   SET value = v.value
  FROM (VALUES
    ('excel.order.title_header', 'ru', 'Заголовок заказа'),
    ('orders.text.import_table_header', 'ru', 'Заголовок заказа')
  ) AS v(text_key, code, value)
  JOIN dictionary_locale l ON l.code = v.code
 WHERE t.text_key = v.text_key AND t.locale_id = l.locale_id;
