-- =====================================================================
-- V130. «Запомнить меня»: погашенный токен живёт ещё полминуты (аудит
-- 11.11.2026, S13).
--
-- ЧТО БЫЛО. Токен удалялся при использовании. Страница при загрузке шлёт
-- несколько запросов разом с одним и тем же токеном: один гасил его и
-- выдавал новый, остальные не находили токен и отвечали «стереть cookie».
-- Ответ «стереть», пришедший последним, затирал новый токен, и следующий
-- запуск браузера снова требовал входа (воспроизведено RememberMeRaceTest).
--
-- КАК ТЕПЕРЬ. Использованный токен не удаляется, а получает last_used_at
-- (колонка была с V46 и не заполнялась). Повторно войти по нему нельзя;
-- но если его погасили только что — меньше 30 секунд назад, — запрос-сосед
-- просто идёт без входа и cookie не трогает. Удаляет такие токены чистка
-- через минуту. Тексты интерфейса токен не трогают вовсе (AuthFilter).
-- =====================================================================

COMMENT ON COLUMN auth_remember_token.last_used_at IS
  'когда токен погашен (заменён новым); погашенный не впускает, чистится через минуту (V130)';

CREATE OR REPLACE FUNCTION auth_remember_cleanup()
RETURNS void
LANGUAGE sql
SECURITY DEFINER SET search_path = dbo, pg_temp AS $$
  DELETE FROM auth_remember_token
   WHERE expires_at < now()
      OR last_used_at < now() - interval '1 minute';
$$;
