-- =====================================================================
-- V60. Убираем тексты постоянного баннера черновика
-- =====================================================================
-- Над незаконченным черновиком висел баннер со списком причин, по которым
-- документ нельзя отправить, а кнопка «Подтвердить» была неактивна.
-- Задумано это было как забота, а вышло наоборот: портал ругался
-- на человека за поля, к которым тот ещё не дошёл, и называл их именами
-- колонок базы — «не заполнены поля: to_warehouse_id, ship_date».
--
-- Теперь иначе: пока человек заполняет документ, портал молчит. Причины
-- он получает тогда, когда сам нажал «Подтвердить», — одной фразой
-- от сервера и с подписями полей, как они названы у него на экране.
-- Фраза собирается из ключей error.ready.* (V57) и остаётся в карточке,
-- пока документ не изменится.
--
-- Поэтому три ключа больше не нужны:
--
--   sku.text.document_not_ready_yet — заголовок того баннера;
--   sku.text.fix_problems_first     — подсказка неактивной кнопки;
--   sku.text.send_document_to_wms   — подсказка активной кнопки, которая
--                                     осталась без пары.
--
-- Не нужен — значит удаляем, а не оставляем «на всякий случай»: ключ,
-- который никто не показывает, переводчик примет за действующую подпись
-- и переведёт в никуда. ON DELETE CASCADE снимет и переводы.
SET search_path = dbo;

DELETE FROM ui_text_key
 WHERE text_key IN ('sku.text.document_not_ready_yet',
                    'sku.text.fix_problems_first',
                    'sku.text.send_document_to_wms');
