-- =====================================================================
-- V47. Переводы заводятся и для выключенного языка
-- =====================================================================
-- V44 выключила казахский и нидерландский: переводов у них нет,
-- и человек, выбрав такой язык, увидел бы английский.
--
-- Тут и вскрылся замкнутый круг. Таблица переводов строилась функцией
-- ui_text_matrix(), а та отдавала только ВКЛЮЧЁННЫЕ языки:
--
--   * язык выключен → колонки в таблице переводов нет → перевод завести
--     нельзя;
--   * переводов нет → включать язык нельзя, иначе клиент увидит портал
--     на языке отката.
--
-- Выход один: ведение переводов не должно зависеть от того, показан
-- язык в переключателе или нет. Это разные вопросы. «Показывать
-- в переключателе» (is_active) решает, можно ли язык ВЫБРАТЬ.
-- Готовить для него тексты можно всегда — иначе новый язык в портале
-- не появится никогда.
SET search_path = dbo;

CREATE OR REPLACE FUNCTION ui_text_matrix()
RETURNS TABLE (text_key varchar, scope varchar, element varchar, owner varchar,
               locale_code varchar, value text)
LANGUAGE sql STABLE SET search_path = dbo AS $$
  SELECT k.text_key, k.scope, k.element, k.owner, l.code, t.value
    FROM ui_text_key k
   CROSS JOIN dictionary_locale l
    LEFT JOIN ui_text t ON t.text_key = k.text_key AND t.locale_id = l.locale_id
   ORDER BY k.scope, k.element, k.text_key, l.sort_order
$$;

COMMENT ON FUNCTION ui_text_matrix() IS
  'Таблица переводов для администрирования: строка на ключ, колонка '
  'на КАЖДЫЙ язык справочника, включая выключенные — иначе новому '
  'языку не подготовить тексты до его включения';
