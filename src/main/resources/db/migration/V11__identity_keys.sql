-- V11__identity_keys.sql
-- Исправление дефекта, найденного при заливке тестовых данных:
-- у числовых первичных ключей не было автогенерации (в словаре демо
-- указан только тип), поэтому любой INSERT без явного id падал.
--
-- enum_* и dictionary_locale оставлены БЕЗ автогенерации намеренно:
-- их id проставляются вручную в V9__reference_data.sql и на эти значения
-- ссылается код. Автоинкремент здесь только мешал бы.
SET search_path = dbo;

ALTER TABLE user_depositor_access  ALTER COLUMN id             ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE user_warehouse_access  ALTER COLUMN id             ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE service_tariff         ALTER COLUMN id             ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE invoice                ALTER COLUMN id             ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE registered_service     ALTER COLUMN id             ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE document_photo         ALTER COLUMN id             ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE depositor_field_label  ALTER COLUMN id             ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE translation            ALTER COLUMN translation_id ADD GENERATED BY DEFAULT AS IDENTITY;

-- Уникальность кодов справочников (в словаре демо не размечена)
ALTER TABLE depositor  ADD CONSTRAINT uq_depositor_code  UNIQUE (code);
ALTER TABLE warehouse  ADD CONSTRAINT uq_warehouse_code  UNIQUE (code);
ALTER TABLE app_user   ADD CONSTRAINT uq_app_user_login  UNIQUE (login);
ALTER TABLE sku        ADD CONSTRAINT uq_sku_code        UNIQUE (depositor_id, code);
ALTER TABLE supplier   ADD CONSTRAINT uq_supplier_code   UNIQUE (depositor_id, code);
ALTER TABLE consignee  ADD CONSTRAINT uq_consignee_code  UNIQUE (depositor_id, code);
ALTER TABLE user_depositor_access ADD CONSTRAINT uq_uda UNIQUE (user_id, depositor_id);
ALTER TABLE user_warehouse_access ADD CONSTRAINT uq_uwa UNIQUE (user_id, warehouse_id);

-- Номера документов уникальны в рамках портала (решение Р2: нумерация сквозная)
ALTER TABLE receipts  ADD CONSTRAINT uq_receipts_document_no  UNIQUE (document_no);
ALTER TABLE orders    ADD CONSTRAINT uq_orders_document_no    UNIQUE (document_no);
ALTER TABLE transfers ADD CONSTRAINT uq_transfers_document_no UNIQUE (document_no);
