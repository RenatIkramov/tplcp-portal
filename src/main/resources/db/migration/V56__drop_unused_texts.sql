-- ---------------------------------------------------------------------
-- 2. Проверка: ключ действительно никому не нужен
-- ---------------------------------------------------------------------
-- Единственная ссылка на ui_text_key в схеме — каталог колонок
-- (table_column.text_key и group_key). Если список захватил такой ключ,
-- миграция падает и называет его: лучше упасть на базе разработчика,
-- чем потерять подпись колонки у клиента.
DO $$
DECLARE
  v_used text;
BEGIN
  SELECT string_agg(DISTINCT k, ', ') INTO v_used
    FROM (
      SELECT c.text_key AS k FROM table_column c
       JOIN _dead_keys d ON d.text_key = c.text_key
      UNION ALL
      SELECT c.group_key FROM table_column c
       JOIN _dead_keys d ON d.text_key = c.group_key
    ) t;
  IF v_used IS NOT NULL THEN
    RAISE EXCEPTION 'Ключ используется в каталоге колонок: %', v_used;
  END IF;
END $$;

