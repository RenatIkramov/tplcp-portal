--
-- Причина. Эти подписи написаны в коде прототипа русским текстом, а
-- перевод к ним находится обратным словарём «русский текст → ключ»
-- (TRU, i18n-fallback.js). V56 искала ключи, которых нет в коде, и сочла
-- эти неиспользуемыми: ключа в коде действительно нет — есть русский
-- текст, по которому ключ находится. Ключи удалили, словарь стал
-- указывать в пустоту, и подпись осталась русской.
--
-- Сверены все подписи кода с обратным словарём: таких «осиротевших»
-- текстов 77. Здесь они возвращаются с прежними переводами
-- (из V26–V55). Повторить ошибку не даст проверка UiTextReverseLookupTest:
-- русский текст из кода, у которого в словаре есть ключ, должен этот ключ
-- находить в каталоге.
