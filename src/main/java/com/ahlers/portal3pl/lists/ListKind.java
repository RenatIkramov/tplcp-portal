package com.ahlers.portal3pl.lists;

/**
 * Список портала: то общее, что есть у поступлений, заказов,
 * перемещений, запасов, товаров и упаковок.
 *
 * <p>ЗАЧЕМ. Отбор, порядок и страницы устроены у всех списков
 * одинаково и держатся на справочнике колонок: подпись, вид фильтра,
 * колонка отбора, колонка сортировки. Разной остаётся ровно пара
 * вещей — из какого представления читать и как называется таблица
 * в справочнике. Их и описывает этот интерфейс.
 *
 * <p>До него механизм знал только про документы: {@code DocumentType}
 * был вписан в фильтры, в страницы и в запрос. Запасам доставалась
 * копия того же самого — а копия расходится с оригиналом на первой же
 * правке, и расходится молча.
 *
 * <p>Всё, что сюда попадает, подставляется в ТЕКСТ запроса, поэтому
 * приходить оно может только отсюда — из перечислений, а не из адреса
 * запроса.
 */
public interface ListKind {

    /** Ключ таблицы в справочнике колонок и кусок адреса: receipts, stock. */
    String tableKey();

    /** Представление, из которого читается список: v_receipts, v_stock_lines. */
    String view();

    /**
     * Вид объекта (enum_object_type) — им отбираются значения
     * справочных фильтров: статусы у поступлений свои, у заказов свои.
     */
    short objectTypeId();

    /**
     * Порядок, в котором список открывается, пока человек не выбрал
     * свой. Это не сортировка, а начало списка: у документов — свежие
     * сверху, у справочников — по коду.
     *
     * <p>Обязан быть УСТОЙЧИВЫМ, то есть заканчиваться колонкой без
     * повторов. Иначе строки с одинаковым значением перескакивают
     * между страницами: один документ человек увидит дважды, другого —
     * ни разу.
     */
    String defaultOrder();

    /**
     * Логическая колонка «запись действует» — если у списка есть архив.
     *
     * <p>Товары из WMS не удаляются, а гасятся: {@code is_active = false}.
     * В списке таких строк по умолчанию нет — иначе справочник со
     * временем состоял бы в основном из того, чем больше не торгуют, —
     * но увидеть их можно: {@code withArchived=true}.
     *
     * <p>Это не фильтр панели, а свойство списка. Фильтром оно быть не
     * может: панель показывает то, что человек выбрал, а здесь отбор
     * действует и тогда, когда человек ничего не выбирал.
     *
     * @return имя логической колонки или {@code null}, если архива нет
     */
    default String archiveColumn() {
        return null;
    }

    /**
     * Колонки склада — для склада, выбранного в шапке портала (V94).
     *
     * <p>Как и архив, это не фильтр панели, а свойство списка: склад
     * в шапке действует на все экраны сразу, и человек его на панели
     * не выбирал. У перемещения складов два, и подходит документ,
     * у которого выбранный склад — отправитель ИЛИ получатель
     * (решение заказчика от 30.10.2026).
     *
     * @return колонки склада; пусто — список по складу не отбирается
     */
    default java.util.List<String> warehouseColumns() {
        return java.util.List.of();
    }
}
